TaskHandle_t ProcessTrigger_handle;

void ProcessTrigger(void *arg){

	while(1){
		// wait for the tasknotify
		ulTaskNotifyTake(pdTRUE, portMAX_DELAY);

		// Send TRIG pulse to PB0
		HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, GPIO_PIN_RESET);
		HAL_Delay(2);

		// send a pulse
		HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, GPIO_PIN_SET);
		HAL_Delay(1); // >10 µs
		HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, GPIO_PIN_RESET);

		snprintf(buffer, sizeof(buffer), "Distance: %d cm\r\n", distance);
		HAL_UART_Transmit(&huart2, (uint8_t *)buffer, strlen(buffer), 10);

		vTaskDelay(pdMS_TO_TICKS(1000));
	}
}

void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin){
	if(GPIO_Pin == GPIO_PIN_13){
		BaseType_t pxHigherPriorityTaskWoken = pdFALSE;
		vTaskNotifyGiveFromISR(ProcessTrigger_handle, &pxHigherPriorityTaskWoken);
		portYIELD_FROM_ISR(pxHigherPriorityTaskWoken);
	}
}
