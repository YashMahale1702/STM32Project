/* Input Capture Callback */
void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim)
{
  if(htim->Channel == HAL_TIM_ACTIVE_CHANNEL_1)
  {
    if(isFirstCaptured == 0)
    {
      icVal1 = HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_1); // Rising edge
      __HAL_TIM_SET_CAPTUREPOLARITY(htim, TIM_CHANNEL_1, TIM_INPUTCHANNELPOLARITY_FALLING);
      isFirstCaptured = 1;
    }
    else if(isFirstCaptured == 1)
    {
      icVal2 = HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_1); // Falling edge
      __HAL_TIM_SET_CAPTUREPOLARITY(htim, TIM_CHANNEL_1, TIM_INPUTCHANNELPOLARITY_RISING);
      isFirstCaptured = 0;

      uint32_t pulseWidth = (icVal2 > icVal1) ? (icVal2 - icVal1) : ((htim->Instance->ARR - icVal1) + icVal2);
      distance = (int)((pulseWidth * 0.0343) / 2); // cm
//      distance = 5;
    }
  }
}
